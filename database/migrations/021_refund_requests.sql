-- Refund requests are tracked separately from payment status because payOS
-- does not expose a merchant refund endpoint in the current integration.
CREATE TABLE IF NOT EXISTS refund_request (
  refund_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES "order"(order_id) ON DELETE CASCADE,
  payment_id BIGINT NOT NULL REFERENCES payment(payment_id) ON DELETE CASCADE,
  requester_user_id UUID REFERENCES "user"(user_id) ON DELETE SET NULL,
  requester_type VARCHAR(20) NOT NULL DEFAULT 'customer',
  reason VARCHAR(1000),
  status_refund_request VARCHAR(20) NOT NULL DEFAULT 'pending',
  provider_reference VARCHAR(255),
  admin_note TEXT,
  processed_by UUID REFERENCES "user"(user_id) ON DELETE SET NULL,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  processed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT refund_request_requester_type_check
    CHECK (requester_type IN ('customer', 'admin')),
  CONSTRAINT refund_request_status_check
    CHECK (status_refund_request IN ('pending', 'processing', 'completed', 'rejected'))
);

CREATE INDEX IF NOT EXISTS idx_refund_request_status
  ON refund_request (status_refund_request, requested_at DESC);

CREATE INDEX IF NOT EXISTS idx_refund_request_payment_id
  ON refund_request (payment_id);
